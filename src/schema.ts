/**
 * Knowledge graph data model.
 *
 * Design invariants (see docs/architecture.md and the design session):
 *   1. Store the LEDGERS, derive the GRAPH. Events/edges/mappings are append-only
 *      evidence; node states and strengths are always recomputable from them.
 *   2. Nodes are propositions at ~one-reasoning-step grain.
 *   3. Edges carry NO scalars — only type (requires/supports) and provenance.
 *      All mass lives in nodes. "Load-bearing" is derived, never stored.
 *   4. known ≠ understood. Known = evidence property (from the event ledger).
 *      Understood = derived structural property (known + requires-subtree held).
 *   5. Candidates (frontier-generated nodes) are a separate state class;
 *      promotion only happens when a session touches them or the learner
 *      picks them as a goal — never automatically.
 *   6. Every event carries session + entryId → jump-to-point provenance.
 */

// ─── Sessions ────────────────────────────────────────────────────────────────

export interface SessionRecord {
	/** pi session UUID (from the session JSONL header). */
	id: string;
	/** ISO timestamp from the header. */
	startedAt: string;
	/** Human topic label (first user message, or /name). */
	topic: string;
	/** Absolute path of the session JSONL. */
	file: string;
}

// ─── Nodes ───────────────────────────────────────────────────────────────────

export type NodeKind = "truth" | "misconception";
export type NodeState = "known" | "not-held" | "candidate";

export interface GraphNode {
	/** Opaque stable id, e.g. "n_a1b2c3". */
	id: string;
	/** The proposition, one reasoning step of grain. */
	statement: string;
	kind: NodeKind;
	/** Domain tag — metadata for visualization, NEVER a merge barrier. */
	domain: string;
	/** candidate = generated by frontier expansion, not yet evidenced. */
	state: NodeState;
	createdAt: number;
}

// ─── Edges ───────────────────────────────────────────────────────────────────

export type EdgeType = "requires" | "supports";

export interface GraphEdge {
	id: string;
	/** The dependency (e.g. "gradient" for gradient descent). */
	from: string;
	/** The dependent (e.g. "gradient descent"). */
	to: string;
	/**
	 * requires  — hard: understanding the target requires holding this.
	 * supports  — soft: the target is more anchored with it, holdable without it.
	 */
	type: EdgeType;
	provenance: Provenance;
}

export interface Provenance {
	session: string;
	/** Entry id in the session JSONL — jump-to-point. */
	entryId: string;
}

// ─── Events (append-only ledger — the source of truth) ──────────────────────

export type EventKind =
	| "probe-correct" // pre-plan quiz, answered correctly (floor evidence)
	| "probe-miss" // pre-plan quiz, wrong answer (ceiling evidence)
	| "dontKnow" // "I don't know" — genuine gap, not a guess
	| "misconception-signaled" // specific wrong belief identified via distractor/note
	| "taught" // node established in Phase 3
	| "check-correct" // post-teach quiz-check, first try
	| "check-incorrect" // post-teach quiz-check, missed
	| "recall-at-delay"; // future: spaced repetition

export interface EventEvidence {
	quizQuestion: string;
	/** What the learner selected (labels). */
	answer: string[];
	/** Free-text note typed with the answer — diagnostic gold. */
	note?: string;
}

export interface KnowledgeEvent {
	id: string;
	node: string;
	kind: EventKind;
	session: string;
	/** Entry id in the session JSONL → jump to the exact point where this happened. */
	entryId: string;
	timestamp: number;
	evidence?: EventEvidence;
}

// ─── Mappings (merge decisions — reversible by design) ──────────────────────

export interface SessionMapping {
	/** Session-local node reference from the extraction JSON. */
	sessionNodeRef: { session: string; localId: string };
	canonicalNode: string;
	decidedBy: "llm-adjudication";
	confidence: number;
	/** Mirror of the session-local statement, for auditability. */
	sessionStatement: string;
}

// ─── Knowing assessment (anchored ordinal rubric — NEVER freehand scalars) ──

export type KnowingLevel =
	| "misconception" // actively holds a wrong version
	| "absent" // dontKnow or wrong with no reasoning
	| "shakily-known" // correct after a miss, or correct with a hedging note
	| "known" // first-try correct
	| "fluent"; // correct AND the note/reasoning shows the right model

/** Ordinal index — deterministic code maps rubric → number, never an LLM. */
export const KNOWING_ORDER: readonly KnowingLevel[] = [
	"misconception",
	"absent",
	"shakily-known",
	"known",
	"fluent",
];

// ─── Extraction pipeline (per-session JSON, Stage 2 output) ─────────────────

export interface ExtractedSession {
	session: string;
	nodes: Array<{
		localId: string;
		statement: string;
		kind: NodeKind;
		domain: string;
	}>;
	edges: Array<{
		from: string; // localId
		to: string; // localId
		type: EdgeType;
	}>;
	events: Array<{
		node: string; // localId
		kind: EventKind;
		entryId: string;
		evidence?: EventEvidence;
	}>;
	knowing: Array<{
		node: string; // localId
		level: KnowingLevel;
		justification: string;
	}>;
}

// ─── Derived state (computed by code, never stored as primary data) ─────────

export interface DerivedNodeState {
	node: string;
	known: boolean;
	knowing: number; // 0..1, from rubric + evidence events
	understood: number; // 0..1, recursive over requires-subtree (aggregation semantics PARKED)
	floating: boolean; // known but not understood
}
